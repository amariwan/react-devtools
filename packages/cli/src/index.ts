#!/usr/bin/env node
import { Command } from "commander";
import {
  findProjectRoot,
  initProject,
  inspectProject,
  removeGeneratedConfig,
} from "./project.js";

function requireRoot(): string {
  const root = findProjectRoot();
  if (!root)
    throw new Error(
      "Could not find a project package.json from the current directory.",
    );
  return root;
}

function printDoctor(root: string): void {
  const report = inspectProject(root);
  console.log(`Project: ${report.root}`);
  for (const check of report.checks) {
    const icon =
      check.status === "pass" ? "✓" : check.status === "warn" ? "!" : "✗";
    console.log(`${icon} ${check.name}: ${check.detail}`);
  }
  if (!report.ok) process.exitCode = 1;
}

const program = new Command()
  .name("next-devtools")
  .description("Next.js DevTools CLI")
  .version("0.0.0");

program
  .command("init")
  .description("Preview or create a missing Next.js DevTools config")
  .option("--write", "Create next.config.mjs when no Next.js config exists")
  .action((options: { write?: boolean }) => {
    const result = initProject(requireRoot(), options.write === true);
    console.log(result.message);
    if (result.action === "preview")
      console.log("Use --write to create this file.");
  });

program
  .command("doctor")
  .description("Diagnose the current Next.js DevTools project")
  .action(() => printDoctor(requireRoot()));

program
  .command("remove")
  .description("Remove only a config generated by next-devtools init")
  .action(() => console.log(removeGeneratedConfig(requireRoot()).message));

program.parse();
