// Compiles the DevTools Tailwind CSS into a self-contained string module so the
// shell can inject it into its shadow root — fully independent of the host app.
/* global console */
import { execFileSync } from "node:child_process";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const input = resolve(root, "src/css/devtools.css");
const output = resolve(root, "dist/devtools.css");
const generated = resolve(root, "src/css/devtools-css.generated.ts");

mkdirSync(resolve(root, "dist"), { recursive: true });

execFileSync(
  "bunx",
  ["@tailwindcss/cli", "-i", input, "-o", output, "--minify"],
  { stdio: "inherit", cwd: root },
);

const css = readFileSync(output, "utf8");
const banner =
  "// AUTO-GENERATED by scripts/build-css.mjs — do not edit by hand.\n";
writeFileSync(
  generated,
  `${banner}export const devtoolsCssText = ${JSON.stringify(css)};\n`,
);
console.log(`Generated devtools-css.generated.ts (${css.length} bytes of CSS)`);
